package Variable;

public class Variable {
    public static void main(String[] args) {
        byte a = 127;
        short b = 32767;
        int i = 2;
        long l = 9223372036854775807L;//long类型字面量需要加L/l
        float f = 3.14f;//float类型后面加F/f
        double d = 3.1415926;
        char c = 'c';
        char c1 = '中';//只存储单个字符
        boolean bool = true;
        boolean bool2 = false;

        //字符串类型
        String name = "tom";
    }
}
